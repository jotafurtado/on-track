#!/usr/bin/env bash
# on-track-init.sh creates the on-track/ tree in a target repo. Idempotent.
# Usage: on-track-init.sh [target-dir]
set -euo pipefail

target="${1:-.}"
script_dir="$(cd "$(dirname "$0")" && pwd)"
assets="$(cd "$script_dir/../assets" && pwd)"
snippet="$assets/AGENTS-snippet.md"
agents="$target/AGENTS.md"
begin_count=0
end_count=0
begin_line=0
end_line=0

legacy_found=0
if [ -e "$target/fast-track-ai" ] || [ -L "$target/fast-track-ai" ]; then
  echo "FAIL: legacy fast-track-ai/ tree found in $target. Rename it to on-track/, replace fast-track-ai/ with on-track/ in the paths inside its files, then rerun." >&2
  legacy_found=1
fi
if [ -f "$agents" ] && grep -q '^<!-- BEGIN MANAGED BLOCK: fast-track-ai' "$agents"; then
  echo "FAIL: legacy fast-track-ai managed block found in $target/AGENTS.md. Delete everything from its BEGIN marker to its END marker, then rerun." >&2
  legacy_found=1
fi
if [ "$legacy_found" -eq 1 ]; then
  exit 1
fi

if [ -f "$agents" ]; then
  marker_info="$(awk '
    /^<!-- BEGIN MANAGED BLOCK: on-track/ { begin_count++; begin_line=NR }
    /^<!-- END MANAGED BLOCK: on-track -->/ { end_count++; end_line=NR }
    END { printf "%d %d %d %d\n", begin_count, end_count, begin_line, end_line }
  ' "$agents")"
  read -r begin_count end_count begin_line end_line <<< "$marker_info"
fi

if ! { [ "$begin_count" -eq 0 ] && [ "$end_count" -eq 0 ]; } &&
  ! { [ "$begin_count" -eq 1 ] && [ "$end_count" -eq 1 ] && [ "$begin_line" -lt "$end_line" ]; }; then
  echo "FAIL: malformed managed markers: BEGIN count $begin_count, END count $end_count (expected 0/0 or 1/1 in order)" >&2
  exit 1
fi

tmp="$(mktemp "${TMPDIR:-/tmp}/on-track-init.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
if [ ! -f "$agents" ]; then
  cat "$snippet" > "$tmp"
elif [ "$begin_count" -eq 0 ]; then
  cat "$agents" > "$tmp"
  printf '\n' >> "$tmp"
  cat "$snippet" >> "$tmp"
else
  if [ "$begin_line" -gt 1 ]; then
    head -n "$((begin_line - 1))" "$agents" > "$tmp"
  fi
  cat "$snippet" >> "$tmp"
  line_count="$(awk 'END { print NR }' "$agents")"
  if [ "$end_line" -lt "$line_count" ]; then
    tail -n "+$((end_line + 1))" "$agents" >> "$tmp"
  fi
fi

mkdir -p "$target/on-track/research" "$target/on-track/refs" \
  "$target/on-track/handoffs/archive" "$target/on-track/assessments" \
  "$target/on-track/decisions" "$target/on-track/tracks"

mkdir -p "$target/on-track/crumbs"
if [ ! -e "$target/on-track/crumbs/.gitignore" ]; then
  printf '*\n' > "$target/on-track/crumbs/.gitignore"
fi

if [ ! -f "$target/on-track/INDEX.md" ]; then
  printf '# INDEX\n\nGenerated by on-track-index. Do not edit by hand.\n' > "$target/on-track/INDEX.md"
fi

if ! [ -f "$agents" ] || ! cmp -s "$tmp" "$agents"; then
  cat "$tmp" > "$agents"
fi

echo "on-track ready in $target"
